export function assertMarkerColorCatalog(
  colors: readonly MarkerColorSeed[] = artmateMarkerColors,
) {
  if (colors.length !== 168) {
    throw new Error(
      `Marker catalog must contain 168 colors, received ${colors.length}`,
    );
  }

  const colorNumbers = new Set<number>();
  const markerNumbers = new Set<string>();
  const positions = new Set<number>();

  colors.forEach((color, index) => {
    if (
      !Number.isInteger(color.colorNumber) ||
      color.colorNumber < 1 ||
      color.colorNumber > 999
    ) {
      throw new Error(`Invalid color number at position ${index + 1}`);
    }
    if (!/^#[0-9A-F]{6}$/.test(color.hex)) {
      throw new Error(`Invalid HEX at position ${index + 1}`);
    }
    if (!/^\d{3}$/.test(color.markerNumber)) {
      throw new Error(`Invalid marker number at position ${index + 1}`);
    }
    if (!color.pantone.trim() || color.pantone.length > 40) {
      throw new Error(`Pantone is required at position ${index + 1}`);
    }
    if (color.catalogPosition !== index + 1) {
      throw new Error(`Marker positions must be sequential from 1 to 168`);
    }
    if (colorNumbers.has(color.colorNumber)) {
      throw new Error(`Duplicate color number ${color.colorNumber}`);
    }
    if (markerNumbers.has(color.markerNumber)) {
      throw new Error(`Duplicate marker number ${color.markerNumber}`);
    }
    if (positions.has(color.catalogPosition)) {
      throw new Error(`Duplicate marker position ${color.catalogPosition}`);
    }

    colorNumbers.add(color.colorNumber);
    markerNumbers.add(color.markerNumber);
    positions.add(color.catalogPosition);
  });
}

assertMarkerColorCatalog();
