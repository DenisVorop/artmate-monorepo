CREATE TABLE "marker_colors" (
  "id" VARCHAR(32) NOT NULL,
  "color_number" INTEGER NOT NULL,
  "pantone" VARCHAR(40) NOT NULL,
  "hex" VARCHAR(7) NOT NULL,
  "catalog_position" INTEGER NOT NULL,
  "marker_number" VARCHAR(3) NOT NULL,

  CONSTRAINT "marker_colors_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "marker_colors_id_check"
    CHECK ("id" ~ '^marker-color-[0-9]{3}$'),
  CONSTRAINT "marker_colors_color_number_check"
    CHECK ("color_number" BETWEEN 1 AND 999),
  CONSTRAINT "marker_colors_pantone_check"
    CHECK (char_length(btrim("pantone")) BETWEEN 1 AND 40),
  CONSTRAINT "marker_colors_hex_check"
    CHECK ("hex" ~ '^#[0-9A-F]{6}$'),
  CONSTRAINT "marker_colors_catalog_position_check"
    CHECK ("catalog_position" BETWEEN 1 AND 168),
  CONSTRAINT "marker_colors_marker_number_check"
    CHECK ("marker_number" ~ '^[0-9]{3}$')
);

CREATE UNIQUE INDEX "marker_colors_color_number_key"
  ON "marker_colors"("color_number");
CREATE UNIQUE INDEX "marker_colors_catalog_position_key"
  ON "marker_colors"("catalog_position");
CREATE UNIQUE INDEX "marker_colors_marker_number_key"
  ON "marker_colors"("marker_number");

